"""Write the three headers the A7 IV helper (helper/readcheck.c) needs to carry the A7S III 5.01 designs.

  work/venv/Scripts/python.exe -I -B gen_s3_write.py

The write levels of readcheck.c are used as they are (levels 5/6, 16/17, 19/20: the code that ran on the A7 IV);
only their tables differ. This writes, into helper/, in the formats helper/gen_expected.py writes:
  expected_sites_ogsq_s3_v5.h             levels 5 and 6: the 14 sites and the changed bytes of the stored record
  expected_words_outsz2560_s3_v1.h        levels 16 and 17: the output-size word and its two guards
  expected_mp_ogfile2560_hs_s_s3_v1.h     levels 19 and 20 (and 18): the encoder-side sites and guards
and for the rear screen (modding/A7S3_PORT.md section 26), built as separate libraries:
  expected_words_lcdratio32_s3_v1.h       levels 16 and 17: the 3:2 picture-ratio constants and six frame-table entries, with their guards
  expected_mp_lcdcycle_s3_v3.h            levels 19 and 20: the C3 routine and its hook in appFw.so (code, written in order)
(lcdfill_s3_v1 and lcdcycle_s3_v1, the first screen designs, ran on a camera on 2026-11-22 and are replaced: section 27.)
Every stock byte is compared with the 5.01 files here. gen_expected.py is not used: its checks name A7 IV
addresses. The same kinds of check are made below with this build's.
"""
import hashlib
import json
import os
import struct
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "helper"
ROOT = HERE.parents[2]
EX = ROOT / "work/extracted/a7s3_501/0700_part_image/dev"
GHIDRA_TARGETS = Path(os.environ.get("A7S3_FW_DIR") or (HERE.parents[5] / "firmwares/a7siii/ghidra_targets"))
DES = ROOT / "modding/designs"


def fw_bytes(rel):
    p = EX / rel
    return (p if p.is_file() else GHIDRA_TARGETS / Path(rel).name).read_bytes()


def write_utf8_lf(path, text):
    with open(path, "w", encoding="utf8", newline="\n") as fh:
        fh.write(text)


BASE = 0x108000
IMAGE_END = 0x108000 + 16132064
SIZE_TABLE = (0x13EC2AC, 0x13EC2AC + 0x80)             # the movie size table (build/emu_size_table.py)
DESC, UNIT, CLIP, COMB = 0x38393C + 0xA02C, 0x38389C + 0xA02C, 0x38BBDC, 0x2D32B8 + 0x1150
hx = lambda b: ", ".join("0x%02x" % x for x in b)


def sites_header(name="ogsq_s3_v5"):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    image = fw_bytes("nflasha8/cpapp-b.bin")
    assert d["artifact_sha256"] == hashlib.sha256(image).hexdigest() and d["mode_id"] == "0x8c0"
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    out = [f"/* Generated by helper_s3/gen_s3_write.py from modding/designs/{name}.json (A7S III 5.01). Do not edit. */",
           "/* %d sites, %d bytes. Stock bytes were compared with cpapp-b.bin %s. */" % (len(sites), sum(len(o) for _, o, _ in sites), d["artifact_sha256"][:16])]
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and image[a - BASE:a - BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and 0xB11000 <= lo and hi <= IMAGE_END, "span outside the image's constant or initialised data"
        for tag, data in (("old", old), ("new", new)):
            out.append("static const u8 site%d_%s[%d] = { %s };" % (k, tag, len(data), hx(data)))
        rows.append("    { 0x%x, %d, site%d_old, site%d_new, 0, 0 }," % (a, len(old), k, k))
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"
    sr = d["stored_record"]
    r_stock, r_new = bytes.fromhex(sr["stock"]), bytes.fromhex(sr["design"])
    offs = [k for k in range(0x15C) if r_stock[k] != r_new[k]]
    assert len(r_stock) == len(r_new) == 0x15C and offs[:2] == [6, 7] and r_stock[6] == r_stock[7] == 1 and 2 < len(offs) <= 128
    out += ["static const unsigned short rec_offs[%d] = { %s };" % (len(offs), ", ".join("0x%x" % k for k in offs)),
            "static const u8 rec_stock[%d] = { %s };" % (len(offs), hx(bytes(r_stock[k] for k in offs))),
            "static const u8 rec_new[%d] = { %s };" % (len(offs), hx(bytes(r_new[k] for k in offs))),
            "#define REC_BYTES %d" % len(offs),
            '#define SITES_TEXT "%d"' % len(sites), '#define ALL_TEXT "%d"' % (len(sites) + 1),
            "/* offs: null for a site whose `length` bytes all change; else the offsets, inside `length` bytes, of the noffs bytes that change. */",
            "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
            "static const struct cp_site cp_sites[] = {"] + rows + ["};"]
    write_utf8_lf(OUT / f"expected_sites_{name}.h", "\n".join(out) + "\n")
    return len(sites), len(offs)


# Where a words design may have a site, and where a guard (the site regions plus these). The rear-screen design: the VDF fit-mode tables
# after the fit function (a guard may cover the function too) and the three frame-table rows (build/build_lcd_s3.py).
WORD_REGIONS = {"outsz2560_s3_v1": ((SIZE_TABLE,), ()),
                "lcdfill_s3_v1": (((0x1E4C78, 0x1E4CBC), (0xD4D744, 0xD4D7BC), (0xD4D7BC, 0xD4D834), (0xD4D834, 0xD4D8AC)), ((0x1E4C28, 0x1E4CBC),)),
                # the two constant words of the picture-ratio function's 16:9 case, and the same three tables; a guard may lie anywhere in
                # that function or in the fit-mode function and its tables
                "lcdratio32_s3_v1": (((0x1E4F98, 0x1E4FA0), (0xD4D744, 0xD4D7BC), (0xD4D7BC, 0xD4D834), (0xD4D834, 0xD4D8AC)),
                                     ((0x1E4C28, 0x1E4CBC), (0x1E4F64, 0x1E5066)))}


def words_header(name="outsz2560_s3_v1"):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert d["kind"] == "ram_words"
    sites = [(int(s["ram_address"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])) for s in d["sites"]]
    guards = [(int(g["ram_address"], 16), bytes.fromhex(g["bytes"])) for g in d["guards"]]
    site_regions, guard_only = WORD_REGIONS[name]
    within = lambda a, n, regions: any(lo <= a and a + n <= hi for lo, hi in regions)
    inside = lambda a, n: within(a, n, site_regions)
    assert sites and all(len(o) == len(n) == 4 and o != n and a % 4 == 0 and inside(a, 4) for a, o, n in sites)
    assert guards and all(0 < len(b) <= 16 and within(a, len(b), site_regions + guard_only) for a, b in guards)
    if "artifact_sha256" in d:                           # a design of words inside the loaded image: every byte is the file's
        image = fw_bytes("nflasha8/cpapp-b.bin")
        assert d["artifact_sha256"] == hashlib.sha256(image).hexdigest()
        assert all(image[a - BASE:a - BASE + 4] == o for a, o, _ in sites) and all(image[a - BASE:a - BASE + len(b)] == b for a, b in guards)
    assert not any(a < sa + 4 and sa < a + len(b) for a, b in guards for sa, _, _ in sites), "a guard overlaps a site"
    out = [f"/* Generated by helper_s3/gen_s3_write.py from modding/designs/{name}.json (A7S III 5.01). Do not edit. */",
           "/* Words of the coprocessor's RAM tables (cpapp-b.bin 5.01): %d site(s), %d guard(s). */" % (len(sites), len(guards)),
           '#define WORDS_DESIGN "%s"' % name,
           "struct ram_word { u32 address; u8 stock[4]; u8 changed[4]; };",
           "static const struct ram_word ram_words[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(o), hx(n)) for a, o, n in sites]
    out += ["};", "/* bytes beside the sites that must be as listed before anything is written */",
            "struct ram_guard { u32 address; u32 len; u8 bytes[16]; };", "static const struct ram_guard ram_guards[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (a, len(b), hx(b.ljust(16, b"\0"))) for a, b in guards]
    out += ["};"]
    write_utf8_lf(OUT / f"expected_words_{name}.h", "\n".join(out) + "\n")
    return len(sites), len(guards)


def mp_header(name="ogfile2560_hs_s_s3_v1"):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    av, lm = fw_bytes("nflasha3/av-cam.bin"), fw_bytes("nflasha15/lib/libmpr.so")
    assert d["artifact_sha256"] == {"libmpr.so": hashlib.sha256(lm).hexdigest(), "av-cam.bin": hashlib.sha256(av).hexdigest()}
    # Code sites (ogfile2560_hs_s_s3_v2, as the A7 IV's ogfile2560_hs_s_v2): single libmpr.so instructions only; the data sites are as before.
    code = {int(p["file_off"], 16) for p in d["patches"] if p["code"]}
    assert all(p["binary"] == "libmpr.so" and len(p["old"]) == 8 and int(p["file_off"], 16) % 4 == 0 for p in d["patches"] if p["code"]), \
        "a code site that is not one libmpr.so instruction"
    tabs = {"av-cam.bin": [], "libmpr.so": []}
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        data = av if p["binary"] == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and data[off:off + len(old)] == old
        tabs[p["binary"]].append((off, 1, old, new))
    # guards, as gen_expected.py --mp: the 4K row of the unit-type table, clip-format row 5, each changed descriptor's profile key
    g_av = [(UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]), (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60])]
    assert struct.unpack("<4I", g_av[0][1]) == (0x486, 0x474, 0x477, 0x47A) and struct.unpack("<4I", g_av[1][1]) == (1, 3840, 2160, 23)
    for x in d["descriptors"]:
        o = DESC + x["descriptor"] * 0x90 + 0x28
        assert struct.unpack_from("<I", av, o)[0] == x["profile_key"]
        g_av.append((o, av[o:o + 4]))
    g_lm = [(0, lm[:16])]
    for off, _, old, new in tabs["libmpr.so"]:
        if off in code:                                          # an instruction: the guards are the two instructions before it and the two after it
            g_lm += [(off + k, lm[off + k:off + k + 4]) for k in (-8, -4, 4, 8)]
            continue
        assert (off - 6 - COMB) % 0x18 == 0 and struct.unpack_from("<H", lm, off - 2)[0] == 3840
        g_lm.append((off - 6, lm[off - 6:off]))
    for binary, guards in (("av-cam.bin", g_av), ("libmpr.so", g_lm)):
        sites = tabs[binary]
        assert not any(a < s + len(o) and s < a + len(b) for a, b in guards for s, _, o, _ in sites), "a guard overlaps a site"
        tabs[binary] = sorted(sites + [(a, 0, b, b"") for a, b in guards])
        assert all(tabs[binary][k][0] + len(tabs[binary][k][2]) <= tabs[binary][k + 1][0] for k in range(len(tabs[binary]) - 1)), "entries overlap"
    first = tabs["av-cam.bin"][0][0] & ~0xFFF
    last = max(a + len(o) for a, _, o, _ in tabs["av-cam.bin"])
    span = ((last - first) + 0xFFF) & ~0xFFF
    assert 0x38B000 <= first and first + span <= 0x3D3000, "an av-cam.bin site lies outside the pages of its tables"
    phoff, phentsize, phnum = struct.unpack_from("<Q", lm, 0x20)[0], *struct.unpack_from("<HH", lm, 0x36)
    load0 = next(struct.unpack_from("<IIQQQQQQ", lm, phoff + k * phentsize) for k in range(phnum) if struct.unpack_from("<I", lm, phoff + k * phentsize)[0] == 1)
    assert load0[2] == 0 and load0[3] == 0 and max(a + len(o) for a, _, o, _ in tabs["libmpr.so"]) <= load0[5], "a libmpr.so site lies outside the first segment"
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    out = [f"/* Generated by helper_s3/gen_s3_write.py from modding/designs/{name}.json (A7S III 5.01). Do not edit. */",
           "/* av-cam.bin %s..., libmpr.so %s... (5.01). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */"
           % (d["artifact_sha256"]["av-cam.bin"][:16], d["artifact_sha256"]["libmpr.so"][:16]),
           '#define MP_DESIGN "%s"' % name,
           "#define MP_AV_FIRST 0x%xUL                 /* file offset of the first page read of av-cam.bin */" % first,
           "#define MP_AV_BYTES 0x%xUL                  /* whole pages: every entry of mp_av lies inside */" % span,
           "struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };"]
    longest = max(len(tabs["av-cam.bin"]), len(tabs["libmpr.so"]))
    if longest > 96:
        out.insert(-1, "#define MP_MAX %d                          /* room for the entries of the longer table (levels 19 and 20) */" % ((longest + 31) & ~31))
    for binary, var in (("av-cam.bin", "mp_av"), ("libmpr.so", "mp_lm")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, binary))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in tabs[binary]]
        out.append("};")
    write_utf8_lf(OUT / f"expected_mp_{name}.h", "\n".join(out) + "\n")
    return {b: (sum(1 for e in t if e[1] == 1), sum(1 for e in t if e[1] == 0)) for b, t in tabs.items()}, hex(first), hex(span)


def mp_appfw_header(name="lcdcycle_s3_v3"):
    """An appFw.so design (build/build_lcdcycle_s3.py or its _v2): code sites, written in the design's order (the cave before the branch into it), put
    back in reverse (MP_LM_ORDERED). The format is that of helper/gen_expected.py --mp for the A7 IV's lcdcycle designs. The av-cam.bin
    table holds only the two standard guards, so nothing is written there. Guards in appFw.so: the file's first 16 bytes, the 16 file
    bytes just before the cave, 16 bytes on each side of the hooked instruction, and the first 16 bytes of each function the routine calls."""
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    av, lib = fw_bytes("nflasha3/av-cam.bin"), fw_bytes("nflasha15/lib/appFw.so")
    assert d["generated_by"] in ("build/build_lcdcycle_s3.py", "build/build_lcdcycle_s3_v2.py", "build/build_lcdcycle_s3_v3.py") and d["library"] == "appFw.so" and all(p["binary"] == "appFw.so" and p["code"] for p in d["patches"])
    assert d["artifact_sha256"] == {"appFw.so": hashlib.sha256(lib).hexdigest()}, "the design was made from another appFw.so"
    g_av = [(UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]), (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60])]
    assert struct.unpack("<4I", g_av[0][1]) == (0x486, 0x474, 0x477, 0x47A) and struct.unpack("<4I", g_av[1][1]) == (1, 3840, 2160, 23)
    phoff, phentsize, phnum = struct.unpack_from("<Q", lib, 0x20)[0], *struct.unpack_from("<HH", lib, 0x36)
    load0 = next(struct.unpack_from("<IIQQQQQQ", lib, phoff + k * phentsize) for k in range(phnum) if struct.unpack_from("<I", lib, phoff + k * phentsize)[0] == 1)
    assert load0[2] == 0 and load0[3] == 0
    mapped = (load0[5] + 0xFFF) & ~0xFFF                 # the mapping at offset 0 holds whole pages (0x5029000 on the tester's camera: its dump)
    assert mapped == 0x5029000
    sites = []
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        assert len(old) == len(new) <= 16 and old != new and lib[off:off + len(old)] == old and off + len(old) <= mapped, "a site's old bytes are not the file's"
        assert p["kind"] == "hook" or off >= load0[5], "a cave byte inside the segment's own bytes"
        sites.append((off, 1, old, new))
    hooks = [s for s, p in zip(sites, d["patches"]) if p["kind"] == "hook"]
    cave0 = min(s[0] for s, p in zip(sites, d["patches"]) if p["kind"] == "cave")
    assert len(hooks) == 1 and d["patches"][-1]["kind"] == "hook", "the hook must come last (apply order)"
    g_lib = [(0, lib[:16]), (cave0 - 0x18, lib[cave0 - 0x18:cave0 - 8])]
    for off, _, _, _ in hooks:
        g_lib += [(off - 16, lib[off - 16:off]), (off + 4, lib[off + 4:off + 20])]
    for fn in sorted(int(v, 16) for v in d["calls"].values()):
        g_lib.append((fn, lib[fn:fn + 16]))
    srt = sorted(sites + [(a, 0, b, b"") for a, b in g_lib])
    assert all(srt[k][0] + len(srt[k][2]) <= srt[k + 1][0] for k in range(len(srt) - 1)), "entries overlap"
    table = [(a, 0, b, b"") for a, b in g_lib] + sites   # guards first (checked only), then the sites in apply order
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    avs = sorted((a, 0, b, b"") for a, b in g_av)
    first = avs[0][0] & ~0xFFF
    span = ((max(a + len(b) for a, _, b, _ in avs) - first) + 0xFFF) & ~0xFFF
    out = [f"/* Generated by helper_s3/gen_s3_write.py from modding/designs/{name}.json (A7S III 5.01). Do not edit. */",
           "/* appFw.so %s... (5.01). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */" % d["artifact_sha256"]["appFw.so"][:16],
           '#define MP_DESIGN "%s"' % name,
           '#define MP_LIB "appFw.so"                 /* the mp_lm table is in appFw.so */',
           "#define MP_LM_ORDERED 1                    /* mp_lm sites in apply order (cave, then the hook); put back in reverse */",
           "#define MP_AV_FIRST 0x%xUL                 /* av-cam.bin: two guards only, nothing written there */" % first,
           "#define MP_AV_BYTES 0x%xUL" % span]
    if len(table) > 96:
        out.append("#define MP_MAX %d                         /* room for the entries of the appFw.so table (levels 19 and 20) */" % ((len(table) + 31) & ~31))
    out.append("struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };")
    for var, rows, what in (("mp_av", avs, "av-cam.bin"), ("mp_lm", table, "appFw.so")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, what))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in rows]
        out.append("};")
    write_utf8_lf(OUT / f"expected_mp_{name}.h", "\n".join(out) + "\n")
    return {"sites": len(sites), "hooks": len(hooks), "guards": len(g_lib), "mapped": hex(mapped), "cave": (hex(cave0), hex(max(s[0] + len(s[2]) for s in sites[:-1])))}


if __name__ == "__main__":
    print("sites header:", sites_header())
    print("words header:", words_header())
    print("mp header v1:", mp_header("ogfile2560_hs_s_s3_v1"))
    print("mp header v2:", mp_header("ogfile2560_hs_s_s3_v2"))
    print("words header, rear screen:", words_header("lcdratio32_s3_v1"))
    print("mp header, C3 routine:", mp_appfw_header())
