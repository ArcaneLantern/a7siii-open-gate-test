"""Design lcdcycle_s3_v2: the C3 preview cycle for the A7S III 5.01, corrected for this camera's 4:3 rear panel.

lcdcycle_s3_v1 ran on an A7S III on 2026-11-22 (modding/A7S3_PORT.md section 27): the hook, the routine, the transfers and the layout
request work (C3 stepped the preview, and 2:1 and 2.4:1 came out as designed), but its "3:2" state showed the stock 16:9 letterbox:
that state relied on the fit word of a 3:2 panel, which this camera does not read. Here the three states are three pairs of the
picture-ratio constants and nothing else decides the picture:

  3:2    height = width x 2/3     the whole sensor area at its true shape (bars of 33 of 600 rows above and below)
  2:1    height = width x 1/2     1.33x anamorphic
  2.4:1  height = width x 5/12    1.6x anamorphic
  (stock 9/16: a start state only; a press goes to 3:2)

and with each state the frame widgets' expected rectangle for a 16:9 picture on a 4:3 panel, rows 0 (rear panel) and 2 (viewfinder)
of their three tables. Everything else is v1: same hook, same cave start, same calls (build/build_lcdcycle_s3.py, whose stub,
compile step and emulator are used here).

  C:\\Python313\\python.exe -B build/build_lcdcycle_s3_v2.py   writes build/lcdcycle_s3_v2/pool.h, modding/designs/lcdcycle_s3_v2.json and
                                                             evidence/a7s3/lcdcycle_s3_v2_emu.json
"""
import hashlib
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_lcdcycle_s3 as v1  # noqa: E402

ROOT, B, CP = v1.ROOT, v1.B, v1.CP
SRC = ROOT / "build/lcdcycle_s3_v2/step.c"
v1.SRC = SRC                                                       # v1.compile_step compiles this file
HOOK1, CAVE, CAVE_END, ZERO_END, STEP_AT, SYMS, TRIGGER, NOOP = v1.HOOK1, v1.CAVE, v1.CAVE_END, v1.ZERO_END, v1.STEP_AT, v1.SYMS, v1.TRIGGER, v1.NOOP
line_of, u32, rect = v1.line_of, v1.u32, v1.rect
RATIOS = [(2, 3), (1, 2), (5, 12), (9, 16)]                        # 3:2, 2:1, 2.4:1, and the stock 16:9
NAMES = ["3:2", "2:1", "2.4:1", "16:9 (stock)"]
BWORDS = [(0x0E00F04F | n << 16, 0x2000BF08 | d << 16) for n, d in RATIOS]     # moveq.w lr, #n ; it eq + moveq r0, #d
RECT_T = [(0, 26, 640, 428), (0, 80, 640, 320), (0, 107, 640, 266), (0, 60, 640, 360)]
RECTS = [rect(r) for r in RECT_T]
CONST = 0x1E4F98
TABLES = (0xD4D744, 0xD4D7BC, 0xD4D834)                            # AF window, its remote-send variant, tracking frame
ENTRIES = [t + 8 * (5 * row + 3) for t in TABLES for row in (0, 2)]  # row 0 rear panel (type 0), row 2 viewfinder; column 3 = a 16:9 picture
LINES = [("B", CONST, (-1, 2, 3), BWORDS, 3)] + [("T%d" % k, e, (-2, -1, 2, 3), RECTS, 3) for k, e in enumerate(ENTRIES)]
SITE_WORDS = {a + 4 * i for _, a, _, cands, _ in LINES for i in range(len(cands[0]))}


def letterbox(width, height, n, d):
    """What the picture-ratio function (0x1e4f64, fit 3) gives a 16:9 picture on a panel of this size: (y, h)."""
    w = width + d if (n, d) == (2, 3) else width                   # its 3:2 case adds the denominator to the width first
    h = (((w << 8) // d) * n >> 8) & 0xFFFE
    return (height - h) // 2, h


def pool():
    """The POOL words and DESC rows of step.c, from the 5.01 image. Equal runs of words are stored once."""
    words, rows, at = [], [], {}

    def put(seq):
        seq = tuple(seq)
        if seq not in at:
            at[seq] = len(words)
            words.extend(seq)
        return at[seq]

    for name, addr, guards, cands, stock in LINES:
        base, nw = (addr - line_of(addr)) // 4, len(cands[0])
        assert addr % 4 == 0 and base + nw <= 16 and all(0 <= base + g < 16 and not 0 <= g < nw for g in guards), name
        assert tuple(u32(addr + 4 * i) for i in range(nw)) == cands[stock], "%s: the stock image does not hold candidate %d" % (name, stock)
        g_at = put(x for g in guards for x in (g & 0xFFFFFFFF, u32(addr + 4 * g)))
        c_at = put(x for cnd in cands for x in cnd)
        rows.append((name, line_of(addr), base, len(guards), len(cands), nw, g_at, c_at))
    assert len(words) < 256
    return words, rows


def pool_h(words, rows):
    out = ["/* Generated by build/build_lcdcycle_s3_v2.py from cpapp-b.bin 5.01 (ILCE-7SM3). Do not edit. */",
           "/* Guards are {word index from the first site word, value} pairs; candidates follow in the order 3:2, 2:1, 2.4:1, stock. */",
           "static const u32 POOL[] = {"]
    for k in range(0, len(words), 8):
        out.append("    " + ", ".join("0x%08xu" % w for w in words[k:k + 8]) + ",     /* %d */" % k)
    out += ["};", "static const struct desc DESC[%d] = {" % len(rows)]
    for name, line, base, ng, ncand, nw, g, c in rows:
        out.append("    { 0x%x, %d, %d, %d, %d, %d, %d },      /* %s: first site word 0x%x */" % (line, base, ng, ncand, nw, g, c, name, line + 4 * base))
    out += ["};", "enum { D_B = 0, D_T0 = 1, D_TLAST = %d };" % (len(rows) - 1)]
    return "\n".join(out) + "\n"


class Emu(v1.Emu):
    def picture(self):
        """Index of the state the constants are in (0..2 the cycle, 3 stock), or the raw words."""
        w = (self.word(CONST), self.word(CONST + 4))
        return BWORDS.index(w) if w in BWORDS else w

    def entries(self):
        return [(self.word(a), self.word(a + 4)) for a in ENTRIES]


def cp_model(bstate=0, rects=None):
    """The seven coprocessor lines from the 5.01 image with the constants and the six table entries set."""
    cp = {line_of(a): bytearray(CP[line_of(a) - B:line_of(a) - B + 64]) for _, a, _, _, _ in LINES}
    put = lambda a, v: struct.pack_into("<I", cp[line_of(a)], a - line_of(a), v)
    put(CONST, BWORDS[bstate][0]), put(CONST + 4, BWORDS[bstate][1])
    for a, k in zip(ENTRIES, rects if rects is not None else [bstate] * 6):
        put(a, RECTS[k][0]), put(a + 4, RECTS[k][1])
    return cp


def rest_same(e):
    for line, b in e.cp.items():
        for off in range(0, 64, 4):
            if line + off not in SITE_WORDS and bytes(b[off:off + 4]) != CP[line + off - B:line + off - B + 4]:
                return False
    return True


def tests(img, code, hook):
    out, fails = [], []

    def case(label, cond, detail=None):
        out.append({"case": label, "ok": bool(cond), **({"detail": detail} if detail else {})})
        if not cond:
            fails.append(label)

    img = bytearray(img)
    img[HOOK1:HOOK1 + 4] = hook
    img = bytes(img)
    new = lambda cp=None, mode=3, fail=None: Emu(img, code, cp or cp_model(), mode, fail)
    released = lambda f: not f.maps and not f.fds and f.n("alloc") == f.n("free")
    bline = line_of(CONST)

    e = new()                                                 # the lcdratio32_s3_v1 state: constants 2/3, tables at the 3:2 rectangle
    seq = []
    for k in range(4):
        okregs, ev = e.press()
        seq.append((okregs, hex(ev), e.picture(), e.entries(), e.n("layout"), rest_same(e)))
    case("four presses in movie mode step 3:2 -> 2:1 -> 2.4:1 -> 3:2 -> 2:1: the constants as designed, one layout call each, event swallowed",
         all(s[0] and s[1] == hex(NOOP) and s[2] == (k + 1) % 3 and s[4] == k + 1 for k, s in enumerate(seq)), [list(map(str, s)) for s in seq])
    case("the same four presses: the six table entries hold the rectangle of each mode, and no other byte of the seven lines changes",
         all(s[3] == [RECTS[(k + 1) % 3]] * 6 and s[5] for k, s in enumerate(seq)))
    case("every buffer unmapped, every descriptor closed, every buffer freed, /dev/mem opened O_RDWR|O_SYNC",
         released(e) and e.n("alloc") == 4 and all(c[2] == "0x101002" and c[1] == "/dev/mem" for c in e.calls if c[0] == "openat"))
    case("the layout request is case 0 (all zero)", all(c[1] == bytes(48) for c in e.calls if c[0] == "layout"))
    case("dlsym is asked for the three libsencore names with RTLD_DEFAULT",
         {(c[1], c[2]) for c in e.calls if c[0] == "dlsym"} == {(0, "_Z9dmm_allocjPj"), (0, "_Z8dmm_freej"), (0, "sen_dma_transfer")})
    case("every transfer is one of the seven 64-byte lines (the model refuses any other); the fit-word line is never touched",
         e.n("xfer") > 0 and not any(c[0] == "xfer" and line_of(0x1E4C7C) in (c[2], c[3]) for c in e.calls))
    f = new(cp_model(bstate=3))                               # the stock image: no screen step applied
    okregs, ev = f.press()
    case("from the stock constants (9/16) and stock tables: one press goes to 3:2, constants and all six entries, one layout call",
         okregs and ev == NOOP and f.picture() == 0 and f.entries() == [RECTS[0]] * 6 and f.n("layout") == 1 and rest_same(f))
    for k in range(3):
        f = new(cp_model(bstate=k))
        okregs, ev = f.press()
        case("starting in state %s: one press goes to %s" % (NAMES[k], NAMES[(k + 1) % 3]), okregs and f.picture() == (k + 1) % 3 and f.entries() == [RECTS[(k + 1) % 3]] * 6)
    for label, mode in (("not movie mode (stills, 2)", 2), ("playback (4)", 4)):
        f = new(mode=mode)
        okregs, ev = f.press()
        case(label + ": event untouched, nothing called, nothing read or written", okregs and ev == TRIGGER and not f.calls and f.picture() == 0 and f.entries() == [RECTS[0]] * 6)
    for ev_id in (0x2150007, 0x2150003, 0x216003E):
        f = new()
        okregs, ev = f.press(ev_id)
        case("event %#x: untouched, nothing called" % ev_id, okregs and ev == ev_id and not f.calls)
    for label, fail in (("dlsym finds no sen_dma_transfer", {"dlsym": "sen_dma_transfer"}), ("dmm_alloc fails", {"alloc": 1}),
                        ("the read of the constants' line fails", {"xfer": (0, bline)}), ("the write of the constants' line fails", {"xfer": (1, bline)}),
                        ("a write is lost (read-back differs)", {"lost": 1})):
        f = new(fail=fail)
        okregs, ev = f.press()
        freed = f.n("free") == (0 if fail.get("alloc") or fail.get("dlsym") else 1)      # a buffer that was never given is not freed
        case(label + ": swallowed, picture unchanged, tables unchanged, no layout call, everything released",
             okregs and ev == NOOP and f.picture() == 0 and f.entries() == [RECTS[0]] * 6 and not f.n("layout") and not f.maps and not f.fds and freed)
    for g in LINES[0][2]:
        cp = cp_model()
        a = CONST + 4 * g
        cp[line_of(a)][a - line_of(a)] ^= 1
        f = new(cp)
        before = {k: bytes(v) for k, v in f.cp.items()}
        okregs, ev = f.press()
        case("the guard word %+d beside the constants not as expected: nothing written anywhere, no layout call" % g,
             okregs and ev == NOOP and {k: bytes(v) for k, v in f.cp.items()} == before and not f.n("xfer", 1) and not f.n("layout"))
    cp = cp_model()
    struct.pack_into("<I", cp[bline], CONST - bline, 0x0E07F04F)       # a numerator that is none of the four
    f = new(cp)
    okregs, ev = f.press()
    case("constants that are none of the four known pairs: nothing written, no layout call", okregs and not f.n("xfer", 1) and not f.n("layout"))
    f = new(cp_model(bstate=0, rects=[3] * 6))                # the constants at 3:2 but the tables stock
    okregs, ev = f.press()
    case("with the 3:2 constants but stock tables: one press writes the 2:1 rectangle into all six", okregs and f.picture() == 1 and f.entries() == [RECTS[1]] * 6 and rest_same(f))
    bad = 0
    for k, (name, addr, guards, _, _) in enumerate(LINES[1:]):
        for g in guards:
            cp = cp_model()
            a = addr + 4 * g
            cp[line_of(a)][a - line_of(a)] ^= 1
            f = new(cp)
            okregs, ev = f.press()
            ent = f.entries()
            if not (okregs and f.picture() == 1 and ent[k] == RECTS[0] and all(v == RECTS[1] for j, v in enumerate(ent) if j != k) and f.n("layout") == 1):
                bad += 1
    case("a guard of any one table line not as expected (24 cases): that entry untouched, the other five written, picture changed, one layout call", not bad)
    for k in (0, 3, 5):
        cp = cp_model()
        a = ENTRIES[k] + 2
        cp[line_of(a)][a - line_of(a)] = 77                   # an entry that is none of the four known rectangles
        f = new(cp)
        before = bytes(f.cp[line_of(a)])
        okregs, ev = f.press()
        others = [v for j, v in enumerate(f.entries()) if j != k]
        case("table entry %d holds no known rectangle: it is left alone, the rest as designed" % k,
             okregs and f.picture() == 1 and others == [RECTS[1]] * 5 and bytes(f.cp[line_of(a)]) == before and f.n("layout") == 1)
    for label, fail, k in (("the read of a table line fails", {"xfer": (0, line_of(ENTRIES[1]))}, 1), ("the write of a table line fails", {"xfer": (1, line_of(ENTRIES[4]))}, 4)):
        f = new(fail=fail)
        okregs, ev = f.press()
        want = [RECTS[0] if j == k else RECTS[1] for j in range(6)]
        case(label + ": picture changed and layout requested all the same, that entry unchanged, everything released",
             okregs and f.picture() == 1 and f.entries() == want and f.n("layout") == 1 and released(f) and f.n("alloc") == 1)
    return out, fails


def main():
    img = v1.locate_file.locate("a7s3_501", "appFw.so").read_bytes()
    # what the function gives for each pair of constants, on an 800x600 and on a 640x480 panel, against the rectangles written to the tables
    for (n, d), want in zip(RATIOS, RECT_T):
        for w, h in ((800, 600), (640, 480)):
            y, hh = letterbox(w, h, n, d)
            got = (0, y * 640 / w, 640, hh * 640 / w)
            assert all(abs(a - b) <= 2 for a, b in zip(got, want)), ((n, d), (w, h), got, want)
    words, rows = pool()
    (SRC.parent / "pool.h").write_text(pool_h(words, rows), encoding="utf8", newline="\n")
    code, stub, step, old, hook = v1.build()
    assert img[HOOK1:HOOK1 + 4] == old and not any(img[v1.SEG_END:ZERO_END]) and CAVE >= v1.SEG_END
    assert CP[0x1E4C78 - B:0x1E4C7C - B] == bytes.fromhex("03000000"), "a 16:9 picture on a 4:3 panel is not letterboxed in the stock table"
    res, fails = tests(img, code, hook)
    for r in res:
        print(("PASS  " if r["ok"] else "FAIL  ") + r["case"])
    if fails:
        raise SystemExit("%d emulated case(s) failed" % len(fails))
    patches = []
    for k in range(0, len(code), 16):
        chunk, was = code[k:k + 16], img[CAVE + k:CAVE + k + 16]
        if chunk == was:
            continue
        patches.append({"binary": "appFw.so", "kind": "cave", "file_off": hex(CAVE + k), "va": hex(CAVE + k), "old": was.hex(), "new": chunk.hex(), "code": True,
                        "note": "cave bytes %#x-%#x%s" % (CAVE + k, CAVE + k + len(chunk), "" if CAVE + k + 16 <= ZERO_END else " (past the zero bytes: the old bytes are the page's copy of the data segment's start)")})
    patches.append({"binary": "appFw.so", "kind": "hook", "file_off": hex(HOOK1), "va": hex(HOOK1), "old": old.hex(), "new": hook.hex(), "code": True,
                    "note": "process_input_event: `%s` -> `b %#x` (the stub does it)" % (v1.HOOK1_OLD, CAVE)})
    design = {"design": "lcdcycle_s3_v2",
              "title": "A7S III 5.01: C3 steps the rear-screen and viewfinder preview 3:2 -> 2:1 -> 2.4:1 in movie mode and keeps the focus frames: the picture-ratio "
                       "constants and the frame widgets' expected rectangle, written from appFw",
              "generated_by": "build/build_lcdcycle_s3_v2.py", "library": "appFw.so", "artifact_sha256": {"appFw.so": hashlib.sha256(img).hexdigest()},
              "coprocessor_image_sha256": hashlib.sha256(CP).hexdigest(),
              "replaces": "lcdcycle_s3_v1 (ran on an A7S III 2026-11-22: C3 worked, 2:1 and 2.4:1 as designed, but its 3:2 state showed the stock 16:9 letterbox)",
              "write_order": "the patches in the listed order to apply (cave, then the hook); the reverse order to put back",
              "trigger": hex(TRIGGER), "ignored_event": hex(NOOP), "calls": {k: hex(v) for k, v in SYMS.items()},
              "cave": {"from": hex(CAVE), "bytes": len(code), "zero_bytes_end": hex(ZERO_END), "page_end": hex(CAVE_END), "inside_zero_bytes": CAVE + len(code) <= ZERO_END},
              "step_routine": "build/lcdcycle_s3_v2/step.c at %#x (%d bytes)" % (STEP_AT, len(step)), "stub_bytes": len(stub),
              "lines": [{"name": n, "line": hex(l), "first_site_word": hex(l + 4 * b), "words": nw, "guards": ng, "candidates": nc} for n, l, b, ng, nc, nw, _, _ in rows],
              "states": {NAMES[k]: {"height": "width x %d/%d" % RATIOS[k], "constants": [hex(x) for x in BWORDS[k]], "frame_rectangle": list(RECT_T[k]),
                                    "on_an_800x600_panel": "%d rows from row %d" % (letterbox(800, 600, *RATIOS[k])[1], letterbox(800, 600, *RATIOS[k])[0])} for k in range(4)},
              "frame_rectangles": {"entries": [hex(a) for a in ENTRIES], "note": "{x, y, w, h} u16 in a 640x480 grid, rows 0 (rear panel of type 0) and 2 (viewfinder), column 3 "
                                                                                 "(16:9 picture) of the three tables; the widgets accept 5 units either way"},
              "goes_with": ["the A7S III open-gate state (ogsq_s3_v5, outsz2560_s3_v1, ogfile2560_hs_s_s3_v1)", "lcdratio32_s3_v1 (sets the 3:2 state without a press; "
                                                                                                                "without it the first press does)"],
              "not_checked": ["on a camera: this design has not run (v1's hook, calls and transfers have)", "the panel-type bytes and which table row the rear panel's widgets use"],
              "note": "put back (level 20) removes the code; the coprocessor words stay in the mode last chosen until a cold boot",
              "patches": patches}
    (ROOT / "modding/designs/lcdcycle_s3_v2.json").write_text(json.dumps(design, indent=1) + "\n", encoding="utf8", newline="\n")
    (ROOT / "evidence/a7s3/lcdcycle_s3_v2_emu.json").write_text(json.dumps({"generated_by": "build/build_lcdcycle_s3_v2.py", "cases": res, "cave_bytes": len(code)}, indent=1) + "\n",
                                                                encoding="utf8", newline="\n")
    print("cave %d bytes from %#x (stub %d, lcd_step %d at %#x); ends at %#x, zero bytes end at %#x; %d patch entries; %d cases pass"
          % (len(code), CAVE, len(stub), len(step), STEP_AT, CAVE + len(code), ZERO_END, len(patches), len(res)))
    for k in range(4):
        y, h = letterbox(800, 600, *RATIOS[k])
        print("   %-13s width x %d/%d: on 800x600, rows %d to %d (%d high) = %.3f : 1" % (NAMES[k], *RATIOS[k], y, y + h, h, 800 / h))


if __name__ == "__main__":
    main()
